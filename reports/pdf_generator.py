from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
import os

def generate_pdf_report(case_id, evidence_data, output_path="reports/Forensic_Report.pdf"):
    """Generates a professional PDF report."""
    # Ensure the directory exists
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    c = canvas.Canvas(output_path, pagesize=letter)
    c.setFont("Helvetica-Bold", 20)
    c.drawString(50, 750, "SHADOWTRACE Forensic Report")
    
    c.setFont("Helvetica", 12)
    c.drawString(50, 720, f"Case ID: {case_id}")
    c.drawString(50, 700, "Generated by: SHADOWTRACE Automated System")
    
    c.setFont("Helvetica-Bold", 14)
    c.drawString(50, 660, "Evidence Summary:")
    
    y_position = 630
    c.setFont("Helvetica", 10)
    
    for evidence in evidence_data:
        c.drawString(50, y_position, f"File: {evidence['filename']}")
        c.drawString(50, y_position - 15, f"SHA-256: {evidence['sha256_hash']}")
        c.drawString(50, y_position - 30, f"Ingested: {evidence['ingested_at']}")
        y_position -= 60
        
        # Add a new page if we run out of space
        if y_position < 100:
            c.showPage()
            y_position = 750
            
    c.save()
    return output_path